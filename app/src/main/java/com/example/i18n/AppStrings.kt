    when (language) {
        AppLanguage.EN -> EnglishStrings
        AppLanguage.BN -> BanglaStrings
    }

fun formatTaka(amount: Double, showSign: Boolean = false): String {
    val isNegative = amount < -0.005
    val absVal = abs(amount)
    val nf = NumberFormat.getNumberInstance(Locale("en", "BD")).apply {
        val hasFraction = abs(absVal - absVal.toLong()) > 0.005
        minimumFractionDigits = if (hasFraction) 2 else 0
        maximumFractionDigits = 2
    }
    val formatted = nf.format(absVal)
    return when {
        isNegative -> "-৳$formatted"
        showSign && amount > 0.005 -> "+৳$formatted"
        else -> "৳$formatted"
    }
}

fun formatDateShort(millis: Long, language: AppLanguage): String {
    val locale = if (language == AppLanguage.BN) Locale("bn", "BD") else Locale.ENGLISH
    return SimpleDateFormat("dd MMM yyyy", locale).format(Date(millis))
}

fun formatDateDayHeader(millis: Long, language: AppLanguage): String {
    val locale = if (language == AppLanguage.BN) Locale("bn", "BD") else Locale.ENGLISH
    return SimpleDateFormat("EEEE, dd MMM yyyy", locale).format(Date(millis))
}
